#!/usr/bin/env python3
"""Write the tag block at the top of every SOP and the browse sections of the README.

Sources of truth:
  * each SOP's "## Control mapping" table: NIST SP 800-53 R5 controls, NIST CSF 2.0
    outcomes and the other frameworks it maps to
  * tools/catalog/catalog.json: status, topics and plain-language keywords

Usage:
  python3 tools/catalog/build.py           rewrite the generated blocks
  python3 tools/catalog/build.py --check   exit 1 if anything is stale or invalid (CI)

Standard library only.
"""
