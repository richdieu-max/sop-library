CTRL_RE = re.compile(r"\b([A-Z]{2})-(\d+)((?:\(\d+\))*)")
CSF_RE = re.compile(r"\b(GV|ID|PR|DE|RS|RC)\.([A-Z]{2})(?:-(\d{2}))?\b")
ID_RE = re.compile(r"SOP-([A-Z0-9]+-\d+)")


def expand_enhancements(fam, num, enh):
    """IA-2(1)(2) is shorthand for IA-2(1) and IA-2(2)."""
    base = f"{fam}-{num}"
    if not enh:
        return [base]
    return [f"{base}({e})" for e in re.findall(r"\((\d+)\)", enh)]


def ctrl_key(c):
    m = re.match(r"([A-Z]{2})-(\d+)(?:\((\d+)\))?", c)
    return (list(FAMILIES).index(m.group(1)) if m.group(1) in FAMILIES else 99,
            int(m.group(2)), int(m.group(3) or 0))


def parse_sop(path):
    text = path.read_text(encoding="utf-8")
    sid = ID_RE.search(path.name).group(1)
    title = re.search(r"^# SOP-[A-Z0-9-]+ · (.+)$", text, re.M).group(1).strip()
    sec = re.search(r"^## Control mapping\n(.*?)(?=^## |\Z)", text, re.S | re.M)
    nist, csf, other = [], [], []
    if sec:
        fw = None
        for line in sec.group(1).splitlines():
            if not line.startswith("|") or line.startswith("|---"):
                continue
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) < 2 or cells[0] == "Framework":
                continue
            if cells[0]:
                fw = cells[0]
            ref = cells[1]
            if fw.startswith("NIST SP 800-53"):
                for fam, num, enh in CTRL_RE.findall(ref):
                    nist += expand_enhancements(fam, num, enh)
            elif fw == "NIST CSF 2.0":
                for fn, cat, sub in CSF_RE.findall(ref):
                    csf.append(f"{fn}.{cat}" + (f"-{sub}" if sub else ""))
            elif fw not in other:
                other.append(fw)
    nist = sorted(OrderedDict.fromkeys(nist), key=ctrl_key)
    csf = list(OrderedDict.fromkeys(csf))
    return {"id": sid, "path": path, "title": title, "text": text,
            "nist": nist, "csf": csf, "other": other}


def load():
    cat = json.loads(CATALOG.read_text(encoding="utf-8"))
    sops = OrderedDict()
    for p in sorted(ROOT.glob("*/SOP-*.md")):
        s = parse_sop(p)
        sops[s["id"]] = s
    return cat, sops


def validate(cat, sops):
    errors = []
    for sid, s in sops.items():
        meta = cat["sops"].get(sid)
        if not meta:
            errors.append(f"{sid}: missing from catalog.json")
            continue
        if not s["nist"]:
            errors.append(f"{sid}: no NIST SP 800-53 R5 controls in its Control mapping table")
        if not s["csf"]:
            errors.append(f"{sid}: no NIST CSF 2.0 row in its Control mapping table")
        for c in s["nist"]:
            if c.split("(")[0] not in CONTROLS:
                errors.append(f"{sid}: control {c} has no title in build.py CONTROLS")
        for c in s["csf"]:
            if c[:5] not in CSF_CATEGORIES:
                errors.append(f"{sid}: CSF category {c[:5]} has no title in build.py CSF_CATEGORIES")
        for t in meta["topics"]:
            if t not in cat["topics"]:
                errors.append(f"{sid}: unknown topic {t}")
        if not 3 <= len(meta["keywords"]) <= 10:
            errors.append(f"{sid}: give 3 to 10 keywords")
    for sid in cat["sops"]:
        if sid not in sops:
            errors.append(f"{sid}: in catalog.json but no SOP file")
    return errors


def tag_block(cat, s):
    meta = cat["sops"][s["id"]]
    status = meta.get("status", cat.get("default_status", "Production"))
    readme = "../README.md"
    topics = " · ".join(f"[{cat['topics'][t]}]({readme}#topic-{t})" for t in meta["topics"])
    grouped = OrderedDict()
    for c in s["nist"]:
        grouped.setdefault(c.split("(")[0], []).append(c)
    nist = " · ".join(f"`{', '.join(v)}` {CONTROLS[b]}" for b, v in grouped.items())
    csf_grouped = OrderedDict()
    for c in s["csf"]:
        csf_grouped.setdefault(c[:5], []).append(c)
    csf = " · ".join(f"`{', '.join(v)}` {CSF_FUNCTIONS[b[:2]]}: {CSF_CATEGORIES[b]}"
                     for b, v in csf_grouped.items())
    lines = [
        TAG_START,
        f"> - **Status:** {status} · **Topics:** {topics}",
        f"> - **Keywords:** {' · '.join(meta['keywords'])}",
        f"> - **NIST SP 800-53 Rev. 5:** {nist}",
        f"> - **NIST CSF 2.0:** {csf}",
    ]
    if s["other"]:
        lines.append(f"> - **Also maps to:** {' · '.join(s['other'])} (see [Control mapping](#control-mapping))")
    lines.append(TAG_END)
    return "\n".join(lines)


def render_sop(cat, s):
    text = s["text"]
    block = tag_block(cat, s)
    if TAG_START in text:
        return re.sub(re.escape(TAG_START) + r".*?" + re.escape(TAG_END), lambda _: block, text, flags=re.S)
    # first time: insert after the "**Family:**" paragraph, else after the first paragraph
    m = re.search(r"^\*\*Family:\*\*.*$", text, re.M) or re.search(r"^# .*\n\n.*$", text, re.M)
    return text[:m.end()] + "\n\n" + block + text[m.end():]


def replace_region(text, name, body):
    start, end = f"<!-- {name}:start (generated by tools/catalog/build.py) -->", f"<!-- {name}:end -->"
    if start not in text:
        raise SystemExit(f"README.md is missing the {name} markers")
    return re.sub(re.escape(start) + r".*?" + re.escape(end), lambda _: f"{start}\n{body}\n{end}", text, flags=re.S)


def link(s):
    return f"[{s['id']}]({s['path'].relative_to(ROOT).as_posix()})"


def render_readme(cat, sops, text):
    # 1. Browse by topic
    rows = ["| Topic | Runbooks |", "|---|---|"]
    for t, label in cat["topics"].items():
        ids = [s for sid, s in sops.items() if t in cat["sops"][sid]["topics"]]
        rows.append(f'| <a id="topic-{t}"></a>**{label}** | {" · ".join(link(s) for s in ids)} |')
    text = replace_region(text, "topics", "\n".join(rows))

    # 2. NIST SP 800-53 coverage by family
    rows = ["| NIST SP 800-53 Rev. 5 family | Controls covered | Runbooks |", "|---|---|---|"]
    for fam, name in FAMILIES.items():
        ctrls = sorted({c for s in sops.values() for c in s["nist"] if c.startswith(fam + "-")}, key=ctrl_key)
        ids = [s for s in sops.values() if any(c.startswith(fam + "-") for c in s["nist"])]
        if ids:
            rows.append(f"| **{fam}** · {name} | {', '.join(ctrls)} | {' · '.join(link(s) for s in ids)} |")
    text = replace_region(text, "nist80053", "\n".join(rows))

    # 3. NIST CSF 2.0 coverage by function and category
    rows = ["| NIST CSF 2.0 function | Category | Runbooks |", "|---|---|---|"]
    for fn, fname in CSF_FUNCTIONS.items():
        for catk, cname in CSF_CATEGORIES.items():
            if not catk.startswith(fn + "."):
                continue
            ids = [s for s in sops.values() if any(c.startswith(catk) for c in s["csf"])]
            if ids:
                rows.append(f"| **{fname}** | {catk} {cname} | {' · '.join(link(s) for s in ids)} |")
    text = replace_region(text, "csf", "\n".join(rows))

    # 4. NIST family column in each catalog table
    def fams(sid):
        return " · ".join(OrderedDict.fromkeys(c[:2] for c in sops[sid]["nist"]))

    def fix_row(m):
        sid = m.group(1)
        if sid not in sops:
            return m.group(0)
        cells = [c.strip() for c in m.group(0).strip().strip("|").split("|")]
        return "| " + " | ".join(cells[:3] + [fams(sid)]) + " |"

    text = re.sub(r"^\| ([A-Z0-9]+-\d+) \| \[.*$", fix_row, text, flags=re.M)
    text = text.replace("| SOP | Runbook | What it covers |\n|---|---|---|",
                        "| SOP | Runbook | What it covers | NIST 800-53 |\n|---|---|---|---|")
    return text


def main():
    check = "--check" in sys.argv[1:]
    cat, sops = load()
    errors = validate(cat, sops)
    if errors:
        print("\n".join(errors))
        return 1
    stale = []
    for s in sops.values():
        new = render_sop(cat, s)
        if new != s["text"]:
            stale.append(s["path"].relative_to(ROOT).as_posix())
            if not check:
                s["path"].write_text(new, encoding="utf-8")
    old = README.read_text(encoding="utf-8")
    new = render_readme(cat, sops, old)
    if new != old:
        stale.append("README.md")
        if not check:
            README.write_text(new, encoding="utf-8")
    if check and stale:
        print("Out of date (run python3 tools/catalog/build.py):\n  " + "\n  ".join(stale))
        return 1
    print(f"{len(sops)} runbooks tagged; {'up to date' if not stale else 'updated ' + str(len(stale)) + ' files'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
